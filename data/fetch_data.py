"""Download the raw sources (cached) and rebuild the processed tables.

    python data/fetch_data.py            # reuse raw files that are still current
    python data/fetch_data.py --force    # download everything again

Raw files go to data/raw/ (git-ignored). The app only needs data/processed/,
which is small enough to commit, so Streamlit Cloud never downloads at startup.
"""
from __future__ import annotations

import argparse
import json
import sys
import zipfile
from datetime import date
from pathlib import Path

import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import config as C  # noqa: E402
from utils import io, prep  # noqa: E402


def main(force: bool = False) -> None:
    paths = {key: io.fetch_and_cache(key, force=force) for key in C.SOURCES}
    manifest = io.read_manifest()
    today = date.today().isoformat()

    with zipfile.ZipFile(paths["population"]) as z:
        name = next(n for n in z.namelist() if n.endswith("_data.csv"))
        with z.open(name) as f:
            pop = prep.build_population(f)

    shapes = prep.load_dep_shapes(paths["departements_fine"])
    with open(paths["regions"], encoding="utf-8") as f:
        region_names = {ft["properties"]["code"]: ft["properties"]["nom"] for ft in json.load(f)["features"]}
    scope = set(pop["dep"]) & set(shapes["dep"])

    print("[build] reading IRVE file")
    raw = pd.read_csv(paths["irve"], dtype=str, low_memory=False)
    points, quality = prep.build_points(raw, shapes, scope, today)

    ev, q_ev = prep.build_ev(paths["ev"])
    ev = ev[ev["dep"].isin(scope)].reset_index(drop=True)
    quality.update(q_ev)
    deps = prep.build_departements(shapes[shapes["dep"].isin(scope)], pop, ev, region_names)
    quality["ev_date"] = str(ev["date"].max().date())
    quality["pop_year"] = int(pop["pop_year"].iloc[0])
    quality["n_departements"] = int(len(deps))
    quality["build_date"] = today
    quality["irve_resource"] = manifest["irve"]["resource_title"]
    quality["irve_last_modified"] = manifest["irve"]["last_modified"]

    gj = prep.build_map_geojson(paths["departements_map"], scope)

    out = C.PROCESSED_DIR
    out.mkdir(parents=True, exist_ok=True)
    points.to_parquet(out / "points.parquet", index=False, compression="zstd")
    deps.to_parquet(out / "departements.parquet", index=False)
    ev.to_parquet(out / "ev_by_dep.parquet", index=False)
    (out / "quality.json").write_text(json.dumps(quality, indent=2, ensure_ascii=False), encoding="utf-8")
    (out / "departements_map.geojson").write_text(json.dumps(gj, separators=(",", ":")), encoding="utf-8")
    write_sources_md(manifest)

    for f in sorted(out.iterdir()):
        print(f"[write] {f.relative_to(C.ROOT)}  {f.stat().st_size / 1e6:.2f} MB")
    print(f"[done] {quality['raw_rows']:,} raw rows -> {quality['clean_rows']:,} clean charging points")


def write_sources_md(manifest: dict) -> None:
    lines = [
        "# Data sources",
        "",
        "Generated by `data/fetch_data.py`. Every file was resolved through the data.gouv.fr API "
        "(`https://www.data.gouv.fr/api/1/datasets/<slug>/`) on the download date shown.",
        "",
    ]
    for key, spec in C.SOURCES.items():
        m = manifest.get(key, {})
        lines += [
            f"## {spec['label']}",
            "",
            f"- Publisher: {spec['publisher']}",
            f"- Dataset page: {m.get('dataset_page', 'n/a')}",
            f"- Resource: {m.get('resource_title', 'n/a')}",
            f"- File URL: {m.get('url', 'n/a')}",
            f"- Resource last modified: {m.get('last_modified', 'n/a')}",
            f"- Downloaded: {m.get('downloaded_at', 'n/a')}",
            f"- Licence code on data.gouv.fr: `{m.get('licence', 'n/a')}`",
            "",
        ]
    lines += [
        "## Policy dates used as chart annotations",
        "",
    ]
    for ev in C.POLICY_EVENTS:
        lines.append(f"- {ev['date']}: {ev['detail']} ({ev['url']})")
    lines += ["",
              "Licence codes: `fr-lo` and `lov2` = Licence Ouverte / Open Licence (Etalab 2.0); "
              "`odc-odbl` = Open Database License 1.0.", ""]
    C.SOURCES_MD.write_text("\n".join(lines), encoding="utf-8")


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--force", action="store_true", help="download every source again")
    main(force=ap.parse_args().force)
